def en(s):
    return '<i class="en">' + s + "</i>"


def card(title, do, code=None, layer1=None, layer2=None, note=None, extra=""):
    parts = ['<div class="card">']
    if title:
        parts.append("<h2>" + title + "</h2>")
    if do:
        parts.append('<p class="do">' + do + "</p>")
    if extra:
        parts.append(extra)
    if code is not None:
        parts.append('<pre class="ltr" dir="ltr">' + code + "</pre>")
    if layer1:
        parts.append('<div class="layer"><b>لایه ۱ — چه شد</b>' + layer1 + "</div>")
    if layer2:
        parts.append(
            '<div class="layer layer2"><b>لایه ۲ — اگر خراب شد</b>' + layer2 + "</div>"
        )
    if note:
        parts.append('<div class="note">' + note + "</div>")
    parts.append("</div>")
    return "\n".join(parts)


